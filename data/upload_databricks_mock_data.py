#!/usr/bin/env python3
"""Upload the gold + ml mock tables to a real Databricks workspace.

Reads DATABRICKS_HOST / DATABRICKS_TOKEN / DATABRICKS_WAREHOUSE_ID from the
project .env (same credentials the app's Databricks MCP connection uses) and,
via the SQL Statement Execution API, creates the `sotf` catalog and its
`gold`/`ml` schemas, then (re)creates and loads each gold/ml table from the
JSONL files generated by generate_databricks_mock_data.py.

Usage:
    python3 upload_databricks_mock_data.py
    python3 upload_databricks_mock_data.py --data ./out_databricks
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path
from typing import Any

import requests
from dotenv import dotenv_values

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import generate_databricks_mock_data as gd  # noqa: E402

BATCH_SIZE = 200


def load_credentials() -> dict[str, str]:
    env = {**dotenv_values(HERE.parent / ".env")}
    missing = [
        k for k in ("DATABRICKS_HOST", "DATABRICKS_TOKEN", "DATABRICKS_WAREHOUSE_ID") if not env.get(k)
    ]
    if missing:
        raise SystemExit(f"Missing in .env: {', '.join(missing)}")
    return env


def run_statement(host: str, token: str, warehouse_id: str, statement: str) -> dict[str, Any]:
    resp = requests.post(
        f"{host.rstrip('/')}/api/2.0/sql/statements",
        headers={"Authorization": f"Bearer {token}"},
        json={
            "warehouse_id": warehouse_id,
            "statement": statement,
            "wait_timeout": "30s",
        },
        timeout=60,
    )
    resp.raise_for_status()
    result = resp.json()
    statement_id = result["statement_id"]
    while result["status"]["state"] in ("PENDING", "RUNNING"):
        time.sleep(1)
        resp = requests.get(
            f"{host.rstrip('/')}/api/2.0/sql/statements/{statement_id}",
            headers={"Authorization": f"Bearer {token}"},
            timeout=60,
        )
        resp.raise_for_status()
        result = resp.json()
    state = result["status"]["state"]
    if state != "SUCCEEDED":
        raise RuntimeError(f"Statement failed ({state}): {result['status'].get('error')}\n{statement}")
    return result


def sql_literal(value: Any, type_name: str) -> str:
    if value is None:
        return "NULL"
    if type_name == "ARRAY":
        items = ", ".join(sql_literal(v, "STRING") for v in value)
        return f"ARRAY({items})"
    if type_name == "BOOLEAN":
        return "TRUE" if value else "FALSE"
    if type_name in ("LONG", "INT", "DOUBLE"):
        return str(value)
    if type_name == "DATE":
        return f"DATE'{value}'"
    if type_name == "TIMESTAMP":
        return f"TIMESTAMP'{value}'"
    escaped = str(value).replace("\\", "\\\\").replace("'", "\\'")
    return f"'{escaped}'"


def create_table_ddl(spec: "gd.TableSpec") -> str:
    columns = ",\n  ".join(f"{c.name} {c.type_text}" for c in spec.columns)
    partition = f"\nPARTITIONED BY ({', '.join(spec.partitioned_by)})" if spec.partitioned_by else ""
    return (
        f"CREATE OR REPLACE TABLE {spec.full_name} (\n  {columns}\n)"
        f"{partition}\nCOMMENT '{spec.comment.replace(chr(39), chr(92) + chr(39))}'"
    )


def insert_statements(spec: "gd.TableSpec", rows: list[dict[str, Any]]) -> list[str]:
    col_names = [c.name for c in spec.columns]
    col_types = {c.name: c.type_name for c in spec.columns}
    statements = []
    for start in range(0, len(rows), BATCH_SIZE):
        batch = rows[start : start + BATCH_SIZE]
        value_rows = []
        for row in batch:
            values = ", ".join(sql_literal(row.get(name), col_types[name]) for name in col_names)
            value_rows.append(f"({values})")
        statements.append(
            f"INSERT INTO {spec.full_name} ({', '.join(col_names)}) VALUES\n"
            + ",\n".join(value_rows)
        )
    return statements


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=HERE / "out_databricks")
    args = parser.parse_args(argv)

    creds = load_credentials()
    host, token, warehouse_id = (
        creds["DATABRICKS_HOST"],
        creds["DATABRICKS_TOKEN"],
        creds["DATABRICKS_WAREHOUSE_ID"],
    )

    def run(statement: str) -> None:
        run_statement(host, token, warehouse_id, statement)

    print(f"Target: {host} (warehouse {warehouse_id})")
    run(f"CREATE CATALOG IF NOT EXISTS {gd.CATALOG}")
    for schema in ("gold", "ml"):
        run(f"CREATE SCHEMA IF NOT EXISTS {gd.CATALOG}.{schema}")
    print(f"Ensured catalog/schemas: {gd.CATALOG}.gold, {gd.CATALOG}.ml")

    for spec in gd.GOLD_AND_ML:
        jsonl_path = args.data / spec.relative_path
        if not jsonl_path.is_file():
            print(f"skip {spec.full_name}: {jsonl_path} not found")
            continue
        rows = [json.loads(line) for line in jsonl_path.read_text(encoding="utf-8").splitlines() if line.strip()]

        run(create_table_ddl(spec))
        for statement in insert_statements(spec, rows):
            run(statement)
        print(f"loaded {spec.full_name}: {len(rows)} row(s)")

    print("Done.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
